#!/usr/bin/env node
// Generate src/shared/AssetIds.luau from the prepared manifest and known IDs.
// Sources (later wins): assets/.cache/upload-cache.json, tools/studio_asset_ids.json.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = path.join(ROOT, "assets", "prepared", "manifest.json");
const CACHE = path.join(ROOT, "assets", ".cache", "upload-cache.json");
const STUDIO = path.join(ROOT, "tools", "studio_asset_ids.json");
const OUT = path.join(ROOT, "src", "shared", "AssetIds.luau");

function readJson(file, fallback) {
  if (!fs.existsSync(file)) return fallback;
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    // 文件存在但不是合法 JSON（例如末尾多了逗号）：必须报错，
    // 否则会被当成"没有任何 ID"，悄悄生成一份全空的 AssetIds.luau。
    console.error(`invalid JSON in ${path.relative(ROOT, file)}: ${error.message}`);
    process.exit(1);
  }
}

function normalizeId(value) {
  if (value == null) return "";
  if (typeof value === "object") value = value.assetId ?? value.id ?? "";
  const text = String(value).trim();
  if (!text) return "";
  if (/^rbxassetid:\/\/\d+$/.test(text)) return text;
  const match = text.match(/(\d+)/);
  return match ? `rbxassetid://${match[1]}` : "";
}

const manifest = readJson(MANIFEST, null);
if (!manifest) {
  console.error("missing assets/prepared/manifest.json; run tools/prepare_assets.py first");
  process.exit(1);
}
const cache = readJson(CACHE, {});
const studio = readJson(STUDIO, {});
const keys = [
  ...Object.keys(manifest.images ?? {}),
  ...Object.keys(manifest.audio ?? {}),
];

const ids = {};
let uploaded = 0;
for (const key of keys) {
  const studioId = normalizeId(studio[key]);
  const cached = cache[key];
  const cachedId = cached && cached.status !== "Rejected"
    ? normalizeId(cached)
    : "";
  const id = studioId || cachedId;
  ids[key] = id;
  if (id) uploaded += 1;
}

const lines = [
  "-- Generated by tools/gen_asset_ids.mjs. Do not edit by hand.",
  "-- Sources: assets/.cache/upload-cache.json, then tools/studio_asset_ids.json.",
  "return table.freeze({",
];
for (const key of keys) {
  lines.push(`    ${key} = ${JSON.stringify(ids[key])},`);
}
lines.push("})", "");

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join("\n"));
console.log(`wrote ${OUT}: ${uploaded}/${keys.length} asset IDs available`);
